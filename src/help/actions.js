/**
 * actions.js — everything Find (Ctrl+K) can do, in the words people use for it.
 *
 * Each action takes you to the place that does it, already open on the thing you named, or does it
 * on the spot. "rename ET-PS-MINI-TINI" → the Product Spec on that ElementType with its ref field
 * open and ET-PS-MINI-TINI-01 typed in.
 *
 *   id      stable; outcomes and tests name it
 *   title   what it does (a function of the bound ref when it takes one)
 *   area    the group it is listed under
 *   words   what people type for it — more is better; the search also matches the title
 *   how     one line: where it is, for anyone who would rather know
 *   needs   'et' | 'position' — takes a ref (from the query, else the current selection)
 *   when    (state) → false hides it (nothing to export, no project open)
 *   run     (ctx) → does it; ctx in help/run.js
 *   cli     the `psr` command doing the same, when there is one
 *   screen  where it lives, to rank it first there
 */
